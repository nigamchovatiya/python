# -----if/else/elif ---conditinal statements---

age = 13

if age >= 18:
    print("You can drive..")
else:
    print("you can't drive..")

# ---- elif   it like else if------

age = 15

if age >= 18:
    print("you can go for solo trip..")
elif age >= 16:
    print("you can go for school trip")
elif age >= 14:
    print("you can go for one day trip.")
else:
    print("not go for any trip..")


